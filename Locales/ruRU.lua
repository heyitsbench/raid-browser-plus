-- 1, 21, 31 ... -> _1; 2-4, 22-24 ... -> _FEW; 0, 5-20, 25-30 ... -> _MANY
function RBP.PluralForm(n)
    local a, b = n % 10, n % 100
    if a == 1 and b ~= 11 then return "_1" end
    if a >= 2 and a <= 4 and (b < 12 or b > 14) then return "_FEW" end
    return "_MANY"
end

-- "Паладин (Свет)"
function RBP.SpecClass(spec, class)
    if not spec or spec == "" then return class or "" end
    if not class or class == "" then return spec end
    return class .. " (" .. spec .. ")"
end

