-- A tree and a class as one German compound: "Heilig-Paladin",
-- "Vergeltungs-Paladin", "Wilder-Kampf-Druide", "Elementar-Schamane".
local SPEC_LINK = { ["Überleben"] = "Überlebens", Gleichgewicht = "Gleichgewichts", Elementarkampf = "Elementar" }
function RBP.SpecClass(spec, class)
    if not spec or spec == "" then return class or "" end
    if not class or class == "" then return spec end
    local s = SPEC_LINK[spec] or spec
    if s:find("ung$") or s:find("heit$") or s:find("schaft$") then s = s .. "s" end
    return (s:gsub(" ", "-")) .. "-" .. class
end

